        # cv2.imwrite(full_path, combined_img)


    # wayback_img_filename = f"wayback_screenshot_{wayback_h}X{wayback_w}.png"
    # cv2.imwrite(os.path.join(out_path_base, wayback_img_filename), wayback_img)
    #
